function formatPrice(price, type) {
  const formatted = new Intl.NumberFormat("es-CO", {
    style: "currency",
    currency: "COP",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(price);

  return type === "arriendo" ? `${formatted} / mes` : formatted;
}

